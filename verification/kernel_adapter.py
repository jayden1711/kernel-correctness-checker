def run_candidate(problem_path: str, candidate_src: str, n_trials: int = 5) -> AdapterResult:
    return _run_model_based(problem_path, candidate_src, n_trials)


def _worker(problem_path: str, candidate_src: str, n_trials: int, queue: mp.Queue):
    try:
        result = run_candidate(problem_path, candidate_src, n_trials)
        queue.put(("OK", result))
    except Exception as e:
        queue.put(("ERROR", f"{type(e).__name__}: {e}\n{traceback.format_exc(limit=3)}"))


def run_with_timeout(
    problem_path: str,
    candidate_src: str,
    n_trials: int = 5,
    timeout_seconds: int = 120,
) -> AdapterResult:
    """
    120s default: KernelBench candidates routinely compile CUDA
    extensions via load_inline on first run, and a cold nvcc compile
    alone can eat 30-60s before a single check runs.
    """
    ctx = mp.get_context("spawn")
    queue = ctx.Queue()
    p = ctx.Process(target=_worker, args=(problem_path, candidate_src, n_trials, queue))
    p.start()
    p.join(timeout=timeout_seconds)

    if p.is_alive():
        p.kill()
        p.join()
        return AdapterResult(problem_file=problem_path, load_error=f"TIMEOUT after {timeout_seconds}s")

    if queue.empty():
        return AdapterResult(problem_file=problem_path, load_error="subprocess exited with no result (crash?)")

    status, payload = queue.get()
    if status == "ERROR":
        return AdapterResult(problem_file=problem_path, load_error=f"subprocess error: {payload}")
    return payload
