"""
verification/kernel_adapter.py

Bridges the operator-agnostic per-call numeric checker (_check_one_call)
to KernelBench's problem/candidate convention.

A problem file defines Model, get_inputs(), get_init_inputs(). Calls are
GENERATED by calling those functions n_trials times. The candidate's
calling convention (ModelNew class vs KernelAgent's kernel_function) is
resolved via a small registry.

REMOVED: TritonBench-G ("split_file") support -- the file-splitting,
test-body-execution, call-spying adapter for TritonBench-G's
separator-delimited files. Deliberately deleted, not deprecated in
place, once KernelBench became the sole real-corpus validation target;
see git history if TritonBench-G evaluation is ever needed again rather
than resurrecting a parallel unused code path.

EXTENDING:
  - New candidate convention (e.g. a third kernel-generation system's
    output format): subclass CandidateConvention, implement detect()
    and build_candidate_fn(), add it to CANDIDATE_CONVENTIONS. Nothing
    else in this file changes.

KNOWN UNVERIFIED PIECE: KernelFunctionConvention's weight-argument
ordering (see its docstring). Confirm against a real composed
kernel_function artifact before trusting those results.
"""

